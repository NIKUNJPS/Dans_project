    print("-" * 64)

    for key, mode in DETAILER_MODES.items():
        missing = REQUIRED_KEYS - set(mode.keys())
        if missing:
            errors.append(f"{key}: missing keys {missing}")
        prompt = mode.get("prompt", "")
        if not isinstance(prompt, str) or len(prompt) < 200:
            errors.append(f"{key}: prompt too short or invalid")
        # Each compiled prompt must carry the integrity / clean-output guarantee.
        if "Integrity" not in prompt and "INTEGRITY" not in prompt and "never invent" not in prompt.lower():
            errors.append(f"{key}: missing integrity guarantee")
        # The clean-output protocol legitimately NAMES the banned tokens in order
        # to forbid them, so strip that block before scanning for real violations.
        scan_target = prompt.replace(CLEAN_OUTPUT_PROTOCOL, "")
        # Lines that enumerate banned phrases in order to forbid them are not violations.
        scan_target = "\n".join(
            ln for ln in scan_target.splitlines()
            if "BANNED" not in ln.upper() and "NEVER IN OUTPUT" not in ln.upper()
        )
        for tok in BANNED_TOKENS:
            if tok in scan_target:
                errors.append(f"{key}: emits banned token '{tok}' outside ban list")
        print(f"{key:<30}{mode.get('group',''):<22}{len(prompt):>12,}")

    # Confirm tri-jurisdiction coverage in the shared detection block.
